// Converts RuneKit's research/discovery-samples.json into fixtures/discovery_samples.lua for corpus_test.lua.
// Usage: node tests/gen_fixtures.mjs [path-to-discovery-samples.json]
// RuneKit stores arrangements 0-based (slot -> module) and levels as words; the fixture is 1-based with level numbers.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = process.argv[2] || 'D:/GitHub/adelheid-software/runekit/research/discovery-samples.json';
const target = join(here, 'fixtures', 'discovery_samples.lua');

const LEVEL = { perfect: 0, excellent: 1, 'very good': 2, good: 3, satisfactory: 4, poor: 5 };
const samples = JSON.parse(readFileSync(source, 'utf8'));

let rows = 0;
let out = `-- Blueprint Helper test fixture. GENERATED by gen_fixtures.mjs from RuneKit's research/discovery-samples.json
-- (${samples.length} recorded puzzles); do not edit by hand. Arrangements are slot -> module, 1-based; levels are
-- 0 Perfect .. 5 Poor; truth is the arrangement the game graded Perfect.
return {
`;
for (const s of samples) {
  const obs = s.observations.map((o) => {
    rows++;
    const level = LEVEL[o.level];
    if (level === undefined) throw new Error(`unknown level ${o.level}`);
    return `{ arrangement = { ${o.arrangement.map((x) => x + 1).join(', ')} }, level = ${level} }`;
  });
  out += `    {\n        materials = { ${s.materials.join(', ')} },\n        truth = { ${s.truth.map((x) => x + 1).join(', ')} },\n`;
  out += `        observations = {\n${obs.map((o) => `            ${o},`).join('\n')}\n        },\n    },\n`;
}
out += '}\n';
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`${samples.length} samples, ${rows} rows written to ${target}`);
